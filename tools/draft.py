#!/usr/bin/env python3
"""Generates C drafts with m2c (https://github.com/matt-kempster/m2c) from the dsd disassembly.

    python tools/draft.py func_0201c2e8            # one function, printed to stdout
    python tools/draft.py --worklist               # every unmatched function of the delinked files
    python tools/draft.py --range 0x0201b41c 0x0201b8dc   # every function in an address range

Drafts are written to build/drafts/<function>.c. They are a starting point, not a solution: types,
names and control flow must be cleaned up by hand until objdiff reports 100%.

m2c is GPL-3.0 and is not shipped with this repository: clone it and set M2C_PATH to its directory
(default: tools/m2c).
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import project  # noqa: E402  (this game's version, ROM name, paths: tools/project.py)
ASM_DIR = project.ASM_DIR
DRAFTS = ROOT / "build" / "drafts"
REPORT = project.REPORT
SYMBOLS = project.SYMBOLS
M2C = Path(os.environ.get("M2C_PATH", ROOT / "tools" / "m2c")) / "m2c.py"


def ensure_disassembly():
    if not ASM_DIR.is_dir() or not any(ASM_DIR.glob("*.s")):
        subprocess.run(["ninja", "dis"], cwd=ROOT, check=True)


def function_asm(name: str) -> str | None:
    pattern = re.compile(rf"^{re.escape(name)}: .*?^\s+arm_func_end {re.escape(name)}$", re.S | re.M)
    for f in ASM_DIR.glob("*.s"):
        m = pattern.search(f.read_text(encoding="utf-8"))
        if m:
            return m.group(0)
    return None


def draft(name: str) -> str:
    asm = function_asm(name)
    if asm is None:
        return f"/* {name}: not found in build/{project.VERSION}/asm (thumb function or wrong name?) */\n"
    tmp = DRAFTS / f"{name}.s"
    tmp.write_text(asm + "\n", encoding="utf-8")
    r = subprocess.run([sys.executable, str(M2C), "-t", "arm-mwcc-c", str(tmp)], capture_output=True, text=True)
    tmp.unlink()
    if r.returncode != 0:
        return f"/* {name}: m2c failed\n{r.stderr.strip()}\n*/\n"
    return f"/* Draft generated by m2c from {name}. Clean it up before use. */\n{r.stdout}"


def worklist_functions() -> list[str]:
    if not REPORT.exists():
        subprocess.run(["ninja", "report"], cwd=ROOT, check=True)
    report = json.loads(REPORT.read_text())
    names = []
    for u in report["units"]:
        if u.get("metadata", {}).get("auto_generated"):
            continue
        for f in u.get("functions", []):
            if float(f.get("fuzzy_match_percent", 0)) < 100.0:
                names.append(f["name"])
    return names


def range_functions(start: int, end: int) -> list[str]:
    names = []
    for line in SYMBOLS.read_text().splitlines():
        m = re.match(r"(\S+) kind:function\(arm.*addr:0x([0-9a-fA-F]+)", line)
        if m and start <= int(m.group(2), 16) < end:
            names.append(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser(description="Generate m2c drafts")
    ap.add_argument("functions", nargs="*")
    ap.add_argument("--worklist", action="store_true", help="Unmatched functions of the delinked files")
    ap.add_argument("--range", nargs=2, type=lambda x: int(x, 0), metavar=("START", "END"))
    args = ap.parse_args()

    if not M2C.exists():
        raise SystemExit(f"m2c not found at {M2C}. Clone https://github.com/matt-kempster/m2c and set M2C_PATH.")
    ensure_disassembly()
    DRAFTS.mkdir(parents=True, exist_ok=True)

    names = list(args.functions)
    if args.worklist:
        names += worklist_functions()
    if args.range:
        names += range_functions(*args.range)
    if not names:
        if args.worklist or args.range:
            print("Nothing to draft: no unmatched function.", file=sys.stderr)
            return
        ap.error("give function names, --worklist or --range")

    for name in names:
        text = draft(name)
        if len(names) == 1 and args.functions:
            print(text)
        (DRAFTS / f"{name}.c").write_text(text, encoding="utf-8")
    print(f"{len(names)} draft(s) written to {DRAFTS.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
