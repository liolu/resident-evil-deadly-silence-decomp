#!/usr/bin/env python3
"""Generates the declarations shared by automatic drafts and given to m2c as context.

    python tools/gen_context.py

Outputs:
  include/m2c_protos.h       prototypes of every function defined in src/ (one per known signature)
  build/auto/m2c_context.c   preprocessed m2c.h + engine.h + m2c_protos.h, for `m2c --context`

With the context, m2c knows the real arguments and return value of the functions a draft calls, so it
stops guessing them. Prototypes keep built-in types and turn unknown struct types into `void *`.
Each prototype is guarded by `M2C_SELF_<name>` so that the file defining a function can include the
header without redeclaring itself with a different type.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import infer_signatures  # noqa: E402
PROTOS = ROOT / "include" / "m2c_protos.h"
CONTEXT = ROOT / "build" / "auto" / "m2c_context.c"

BUILTIN = {"void", "char", "short", "int", "long", "float", "double", "signed", "unsigned", "const", "volatile",
           "s8", "u8", "s16", "u16", "s32", "u32", "s64", "u64", "f32", "f64", "M2C_UNK", "fx32", "VecFx32"}
DEFINITION = re.compile(r"^(?!static\b|asm\b)([A-Za-z_][\w \*]*?)\b(\w+)\(([^()]*)\) \{$", re.M)


def engine_types() -> set[str]:
    """Type names include/engine.h defines (typedefs, structs): m2c gets engine.h as context too, so prototypes using
    them stay precise. Matched functions with such types teach their callers and callees the real layout."""
    p = ROOT / "include" / "engine.h"
    text = p.read_text(encoding="utf-8") if p.exists() else ""
    names = set(re.findall(r"\btypedef\b[^;{]*?\b(\w+)\s*;", text)) | set(re.findall(r"\}\s*(\w+)\s*;", text))
    return names | {"struct", "union", "enum"} | set(re.findall(r"\b(?:struct|union|enum)\s+(\w+)\s*\{", text))


KNOWN = BUILTIN | engine_types()


def simplify(decl: str) -> str | None:
    """Keeps a type made of built-in or engine.h words, maps other pointers to `void *`; None if not representable."""
    decl = decl.strip()
    words = re.findall(r"[A-Za-z_]\w*", decl.replace("*", " "))
    stars = decl.count("*")
    if all(w in KNOWN for w in words):
        return decl
    return "void *" if stars else None


def param_type(param: str) -> str | None:
    param = param.strip()
    if param in ("", "void"):
        return "void"
    m = re.match(r"(.*?)(\w+)$", param)  # drop the parameter name
    return simplify(m.group(1)) if m else None


def main():
    seen = {}
    for path in sorted((ROOT / "src").rglob("*.c")):
        for m in DEFINITION.finditer(path.read_text(encoding="utf-8")):
            ret, name, params = m.group(1), m.group(2), m.group(3)
            ret_t = simplify(ret)
            params_t = [param_type(p) for p in params.split(",")] if params.strip() else ["void"]
            if ret_t is None or None in params_t or name in seen or name == "main":
                continue
            seen[name] = f"{ret_t} {name}({', '.join(params_t)});".replace("* ", "*").replace(" *", " *")
    # Functions that a file including m2c_protos.h already declares itself (m2c `/* extern */` lines) must stay out:
    # a second declaration with other types would not compile.
    excluded = set()
    for path in (ROOT / "src").rglob("*.c"):
        text = path.read_text(encoding="utf-8")
        if "m2c_protos.h" in text:
            excluded.update(re.findall(r"\b(\w+)\([^()]*\);\s*/\* extern \*/", text))
    seen = {k: v for k, v in seen.items() if k not in excluded}
    engine = (ROOT / "include" / "engine.h").read_text(encoding="utf-8")
    lines = ["/* Generated by tools/gen_context.py: do not edit. */", "#ifndef M2C_PROTOS_H", "#define M2C_PROTOS_H",
             "// clang-format off", '#include "m2c.h"', '#include "engine.h"', "// clang-format on", ""]
    for name, proto in sorted(seen.items()):
        if re.search(rf"\b{name}\(", engine):
            continue
        lines += [f"#ifndef M2C_SELF_{name}", proto, "#endif"]
    # Guessed signatures (argument count, value returned or not) for functions without a real prototype yet
    guessed = 0
    if "--no-guess" not in sys.argv:
        for name, proto in sorted(infer_signatures.infer().items()):
            if name in seen or name in excluded or name == "main" or re.search(rf"\b{name}\(", engine):
                continue
            lines += [f"#ifndef M2C_SELF_{name}", proto, "#endif"]
            guessed += 1
    lines += ["", "#endif", ""]
    PROTOS.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    CONTEXT.parent.mkdir(parents=True, exist_ok=True)
    pre = subprocess.run(["gcc", "-E", "-P", "-I", str(ROOT / "include"), "-x", "c", str(PROTOS)],
                         capture_output=True, text=True, check=True).stdout
    # m2c cannot use macros: M2C_FIELD only exists in drafts, never in declarations
    CONTEXT.write_text(pre, encoding="utf-8", newline="\n")
    print(f"{len(seen)} prototypes + {guessed} guessed -> {PROTOS.relative_to(ROOT)}, context -> {CONTEXT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
